-- P-8 · 알림이 어느 실행(읽기)에서 생겼는지 알림 줄에 직접 적는다.
-- 변경은 사람들이 공유해서(변경 → 수집 자료 → 실행 경로) 두 번째 사용자의 판단이 첫 번째 사용자의 실행에 기록될 수 있다(불변 5).
-- 이 칸은 읽기를 실행한 본인의 알림에만 채우고, 남의 알림은 비워 둔다(null = 연결된 실행 없음, 흐름 화면은 회색).
-- 쓰기는 서버(서비스 키)만: 알림 쓰기 권한은 그대로 두고 칸만 더한다.
alter table public.alerts add column run_id uuid references public.runs (id);
